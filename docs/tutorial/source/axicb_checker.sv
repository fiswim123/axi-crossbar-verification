//=============================================================================
// 工程名称: AXI Crossbar 互联设计
// 文件名称: axicb_checker.sv
// 文件功能: 仿真断言与错误检查宏定义 (Checker Macro)
// 模块描述:
//   本文件定义了跨模块使用的错误检查宏 `CHECKER(condition, msg)。
//   当满足指定错误条件 (condition 为真) 时，打印带红色高亮的错误信息并立即终止仿真。
//   在 AXI Crossbar 顶层及各子模块中，用于捕获非法参数配置 (如非法通道位宽、
//   不支持的模式等)，防止由于错误参数配置导致硬件行为异常或仿真死锁。
//=============================================================================

`ifndef AXICB_CHECKERS
`define AXICB_CHECKERS

//-----------------------------------------------------------------------------
// 宏名称: `CHECKER(condition, msg)
// 参数说明:
//   - condition: 触发错误的布尔表达式。当为 1 (真) 时表示检测到非法情况
//   - msg      : 报错时向终端打印的字符串信息
// 实现逻辑:
//   如果 condition 为真，利用 ANSI 控制码 \033[1;31m 将输出变为粗体红色，
//   打印包含 msg 的 ERROR 信息，随后调用 $finish(1) 携带错误码退出仿真。
//-----------------------------------------------------------------------------
`define CHECKER(condition, msg)\
    if (condition) begin \
        $display("\033[1;31mERROR: %s\033[0m", msg); \
        $finish(1); \
    end

`endif
