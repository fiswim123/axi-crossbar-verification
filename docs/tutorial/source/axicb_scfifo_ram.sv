//=============================================================================
// 工程名称: AXI Crossbar 互联设计
// 文件名称: axicb_scfifo_ram.sv
// 文件功能: 同步 FIFO 存储体 - 存储器 RAM 实现方式 (Inferred RAM Storage)
// 模块描述:
//   本模块为同步 FIFO 控制器 (axicb_scfifo) 提供基于 RAM 推断的物理存储体。
//   与 regfile 实现方式相比，RAM 实现的特点包括:
//   1. 存储阵列无全局复位网络 (No Memory Reset):
//      - 仅通过读写指针的复位即可保证逻辑上的“空”，无需浪费昂贵的触发器复位树。
//      - 综合工具可将其自动推断为 FPGA 的 Block RAM (BRAM) 或 ASIC 中的 SRAM/Latch 阵列。
//   2. 读数据模式可配置 (参数 FFD_EN):
//      - FFD_EN = 0: 组合读 (异步读)，读地址变化当拍立即输出数据 (Latency = 0)。
//      - FFD_EN = 1: 寄存读 (同步读)，读出数据经过 D 触发器寄存输出 (Latency = 1)。
//=============================================================================

`timescale 1 ns / 1 ps
`default_nettype none

module axicb_scfifo_ram

    #(
        //---------------------------------------------------------------------
        // 参数配置
        //---------------------------------------------------------------------
        // 地址总线位宽，决定 FIFO 深度为 2**ADDR_WIDTH 个条目
        parameter ADDR_WIDTH = 8,
        // 数据总线位宽，决定每个条目的位宽 (单位: bit)
        parameter DATA_WIDTH = 8,
        // 读出口寄存器使能: 0=组合输出 (0延迟), 1=触发器打拍输出 (1时钟周期延迟)
        parameter FFD_EN     = 0
    )(
        // 全局信号
        input  wire                   aclk,      // 统一工作时钟

        // 写端口 (Write Port)
        input  wire                   wr_en,     // 存储体写使能，高电平时在时钟上升沿执行写入
        input  wire  [ADDR_WIDTH-1:0] addr_in,   // 写入地址 (通常连接 FIFO 写指针低位)
        input  wire  [DATA_WIDTH-1:0] data_in,   // 待写入的数据有效载荷

        // 读端口 (Read Port)
        input  wire  [ADDR_WIDTH-1:0] addr_out,  // 读出地址 (通常连接 FIFO 读指针低位)
        output logic [DATA_WIDTH-1:0] data_out   // 读出的数据有效载荷
    );

    //-------------------------------------------------------------------------
    // 存储阵列定义: 深度为 2**ADDR_WIDTH，位宽为 DATA_WIDTH
    //-------------------------------------------------------------------------
    logic [DATA_WIDTH-1:0] ram [2**ADDR_WIDTH-1:0];

    //-------------------------------------------------------------------------
    // 写操作进程: 同步单端口写入
    // 注意: 这里没有 reset 分支，上电或复位时 RAM 内部数据为不确定值 (X 或随机值)。
    // FIFO 的正确性完全依靠外部指针控制，只有被成功写入且未被覆盖的地址才会被读取。
    //-------------------------------------------------------------------------
    always @ (posedge aclk) begin
        if (wr_en) begin
            ram[addr_in] <= data_in; // 时钟上升沿将输入数据锁存到指定地址
        end
    end

    //-------------------------------------------------------------------------
    // 读操作进程: 支持组合直通读或寄存读
    //-------------------------------------------------------------------------
    generate if (FFD_EN==1) begin: WITH_FFD
        // 模式 1: 读出数据寄存一拍 (同步读)
        // 优点: 改善时序路径，切断 RAM 读出到外部逻辑的组合长路径
        // 缺点: 增加 1 个时钟周期的读延迟，需要外部控制器相应调整空满预测
        always @ (posedge aclk) begin
            data_out <= ram[addr_out];
        end
    end else begin: NO_FFD
        // 模式 2: 纯组合读 (异步读)
        // 优点: 读地址给出的当拍立即获得有效数据，在 axicb_scfifo 中实现单周期读出
        // 缺点: 读地址到输出数据是纯组合逻辑路径
        assign data_out = ram[addr_out];
    end
    endgenerate

endmodule

`resetall
